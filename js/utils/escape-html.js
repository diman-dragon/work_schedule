/* utils/escape-html.js
 * Экранирование текста перед вставкой в innerHTML.
 *
 * Автобус, маршрут и другие текстовые поля дня приходят от пользователя (или
 * из импортированного JSON/данных с другого устройства через облако) и
 * вставлялись прямо в HTML-строки без какой-либо обработки — как в виде
 * текста, так и внутри HTML-атрибутов (data-value="...", aria-label="...").
 * Значение вроде `"><img src=x onerror=...>` в поле "маршрут" в таком виде
 * выполнилось бы как настоящий HTML/JS при отрисовке дня в календаре или
 * чипов "недавние автобусы/маршруты". escapeHtml() делает такую вставку
 * безопасной — используется везде, где пользовательский текст идёт в
 * innerHTML (см. calendar/render.js, day-modal/render-recent-*.js).
 */
function escapeHtml(value){
  return String(value == null ? '' : value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
